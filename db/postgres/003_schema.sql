    CONSTRAINT ck_pk_sciezka_zaleznosci_type
        CHECK (typ IN ('KOLEJNOSC', 'WARUNEK')),
    CONSTRAINT ck_pk_sciezka_zaleznosci_self
        CHECK (element_od_id <> element_do_id)
);

