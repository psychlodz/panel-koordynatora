CREATE TABLE IF NOT EXISTS pk_zadania (
    zadanie_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    epizod_id bigint NOT NULL,
    element_id bigint,
    status text NOT NULL DEFAULT 'DO_ZAPLANOWANIA',
    data_wymagana_do date,
    data_zaplanowana timestamptz,
    data_realizacji timestamptz,
    zrodlo text NOT NULL DEFAULT 'PROGRAM',
    eskulap_system text,
