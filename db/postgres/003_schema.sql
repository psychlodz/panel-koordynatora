CREATE TABLE IF NOT EXISTS pk_patient_cache (
    patient_cache_id bigserial PRIMARY KEY,
    pacjent_id_eskulap text NOT NULL UNIQUE,
    pesel_enc bytea,
    imie_enc bytea,
    nazwisko_enc bytea,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz
);

CREATE OR REPLACE FUNCTION kompas_encrypt_patient_text(value text)
RETURNS bytea
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
DECLARE
    data_key text;
BEGIN
    IF value IS NULL THEN
        RETURN NULL;
    END IF;
    data_key := NULLIF(current_setting('kompas.data_key', true), '');
    IF data_key IS NULL THEN
        RAISE EXCEPTION
            'Brak klucza sesji kompas.data_key'
            USING ERRCODE = '22023';
    END IF;
    RETURN pgp_sym_encrypt(value, data_key, 'cipher-algo=aes256');
END;
$$;

CREATE OR REPLACE FUNCTION kompas_decrypt_patient_text(value bytea)
RETURNS text
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
DECLARE
    data_key text;
BEGIN
    IF value IS NULL THEN
        RETURN NULL;
    END IF;
    data_key := NULLIF(current_setting('kompas.data_key', true), '');
    IF data_key IS NULL THEN
        RAISE EXCEPTION
            'Brak klucza sesji kompas.data_key'
            USING ERRCODE = '22023';
    END IF;
    RETURN pgp_sym_decrypt(value, data_key);
END;
$$;

COMMIT;
